/* Refresh the small, static shelf index after editing either book. No build step on the site. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const read = name => fs.readFileSync(path.join(__dirname, name), 'utf8');
const context = vm.createContext({window:{}});
for (const name of ['content', 'enrichment', 'sources', 'olympiad']) {
  vm.runInContext(read('microbiology/' + name + '.js'), context);
}
const book = context.window.MICROBOOK;
const plain = html => html.replace(/<[^>]+>/g, '').replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/\s+/g, ' ').trim();
function summary(text) {
  const line = plain(text || '');
  if (line.length <= 175) return line;
  return line.slice(0, 172).replace(/\s+\S*$/, '') + '…';
}
const lesson = read('replication/index.html');
const units = new Map([...lesson.matchAll(/<section\b([^>]*\bclass="unit"[^>]*)>([\s\S]*?)(?=<section\b[^>]*\bclass="unit"|<\/article>)/g)].map(([,attrs,html]) => {
  const id = attrs.match(/\bid="([^"]+)"/)[1];
  return [id, [id, plain(html.match(/<h2>(.*?)<\/h2>/s)[1]), summary(html.match(/<p>(.*?)<\/p>/s)?.[1])]];
}));
const topic = section => [section.id, section.title, summary(section.lead || section.body.match(/<p>(.*?)<\/p>/s)?.[1])];
const repGroup = (name, ids) => ({name, topics:ids.split(' ').map(id => {
  if (!units.has(id)) throw Error('Missing section ' + id);
  return units.get(id);
})});
const replication = {
  title:'Репликация ДНК', first:'evidence', groups:[
    repGroup('Принцип копирования', 'evidence chemistry'),
    repGroup('Инициация', 'bacterial-origin licensing'),
    repGroup('Работа вилки', 'fork clamps okazaki maturation bubble'),
    repGroup('Завершение и сравнение', 'termination ends comparison'),
    {name:'Материалы', topics:[['start','Анимация репликации','Семь последовательных стадий с управлением воспроизведением.'], units.get('sources')]}
  ]
};
if (units.size !== replication.groups.flatMap(g => g.topics).length - 1) throw Error('Unindexed replication section');
const microbiology = {
  title:'Бактериальная клетка', first:book.chapters[0].sections[0].id, groups:[
    {name:'Опорные знания', landing:'primer', topics:book.primer.map(topic)},
    ...book.chapters.map(c => ({name:c.title, landing:'chapter:'+c.id, topics:c.sections.map(topic)})),
    {name:'Справочник', topics:[
      ['home','Обзор учебника'], ['atlas','Атлас микрофотографий'], ['glossary','Словарь'],
      ['recall','Вопросы для повторения'], ['guide','Как работать с учебником'], ['sources','Источники и авторство']
    ]}
  ]
};
const generated = '/* Generated by build-book-index.cjs from the published books. */\nwindow.PhagiBookIndex = ' +
  JSON.stringify({replication, microbiology}, null, 1) + ';\n';
if (process.argv.includes('--check')) {
  if (read('book-index.js') !== generated) throw Error('Regenerate book-index.js');
} else fs.writeFileSync(path.join(__dirname,'book-index.js'), generated);
